def build_segments(sequence):
    """切出連續區間，start/end 為原始的零起算索引（end 不包含）。"""
    segments = []
    for index, label in enumerate(sequence):
        if not segments or segments[-1]["label"] != label:
            segments.append({"start": index, "end": index + 1, "label": label})
        else:
            segments[-1]["end"] = index + 1
    return segments


def score_changes(changes):
    """對相鄰值計分；查表不分方向，紀錄仍保留實際方向及所有並列。"""
    scored = []
    for left, right in zip(changes, changes[1:]):
        scored.append((left, right, poseChangePoint[tuple(sorted((left, right)))]))
    maximum = max((score for _, _, score in scored), default=None)
    best = list(dict.fromkeys((a, b) for a, b, score in scored if score == maximum))
    return maximum, best


def analyze_sequence(sequence, con_k, csv_k):
    """逐一刪除中間短區間，再將有效影格合併成數字變化。"""
    if con_k <= 0 or csv_k <= 0:
        raise ValueError("con_k and csv_k must be positive")
    if any(label not in range(1, 6) for label in sequence):
        raise ValueError("pose labels must be integers from 1 to 5")
    segments = build_segments(sequence)
    original_changes = [segment["label"] for segment in segments]
    filtered_x, filtered_y = [], []
    for index, segment in enumerate(segments):
        length = segment["end"] - segment["start"]
        if index in (0, len(segments) - 1) or length >= con_k:
            filtered_x.extend(range(segment["start"], segment["end"]))
            filtered_y.extend([segment["label"]] * length)
    changes = []
    for segment in build_segments(filtered_y):
        changes.append(segment["label"])
        if segment["end"] - segment["start"] >= csv_k:
            changes.append(segment["label"])
    maximum, best = score_changes(changes)
    original_maximum, original_best = score_changes(original_changes)
    return {
        "original_changes": original_changes,
        "filtered_x": filtered_x,
        "filtered_y": filtered_y,
        "label_changes": changes,
        "max_score": maximum,
        "max_changes": best,
        "original_max_score": original_maximum,
        "original_max_changes": original_best,
        "valid_frames": len(filtered_y),
        "removed_frames": len(sequence) - len(filtered_y),
    }


def plot_sequence(x, y, total_frames, path):
    """尺寸、點線、刻度、標籤與有效影格連線。"""
    import importlib.util
    import sys
    from pathlib import Path
    if importlib.util.find_spec("matplotlib") is None:
        local_dependencies = Path(__file__).resolve().parent / ".ablation-deps"
        if local_dependencies.is_dir():
            sys.path.insert(0, str(local_dependencies))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.plot(x, y, marker="o", linewidth=1)
    ax.set_xlabel("frame")
    ax.set_ylabel("pose", rotation="vertical")
    ax.grid(True)
    ax.set_xticks(list(range(0, total_frames, 30)))
    ax.tick_params(axis="x", labelrotation=45)
    ax.set_yticks([1, 2, 3, 4, 5], ["A1", "A2", "A3", "A4", "A5"])
    ax.set_ylim(0, 6)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def require_excel_dependencies():
    """在開始繪圖前檢查 Excel 匯出依賴。"""
    try:
        import openpyxl
    except ModuleNotFoundError as exc:
        if exc.name != "openpyxl":
            raise
        import sys
        raise RuntimeError(
            f'Excel 匯出需要 openpyxl，請執行："{sys.executable}" -m pip install openpyxl'
        ) from exc


def export_excel(records, workbook_path):
    """直接使用 Python 匯出 Excel，不依賴 Node.js 或外部匯出腳本。"""
    import json
    from math import ceil
    from pathlib import Path
    require_excel_dependencies()
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.worksheet.table import Table, TableStyleInfo

    workbook_path = Path(workbook_path)
    workbook_path.parent.mkdir(parents=True, exist_ok=True)
    workbook = Workbook()
    workbook.remove(workbook.active)
    headers = ["影片", "con_k", "csv_k", "原始數字序列變化", "有效數字序列變化",
               "最大分數", "最高分數字變化", "有效影格數", "刪除影格數", "原始最大分數",
               "原始最高分數字變化", "有效數字序列（逐影格）"]

    def sequence_text(values):
        return " → ".join(map(str, values))

    def pairs_text(values):
        return "; ".join(sequence_text(pair) for pair in values) or "無相鄰變化"

    for group in ("con_sweep", "csv_sweep"):
        sheet = workbook.create_sheet(group)
        sheet.append(headers)
        for row in records:
            if row["experiment"] != group:
                continue
            sheet.append([
                row["pose"], row["con_k"], row["csv_k"],
                sequence_text(row["original_changes"]), sequence_text(row["label_changes"]),
                row["max_score"], pairs_text(row["max_changes"]), row["valid_frames"],
                row["removed_frames"], row["original_max_score"],
                pairs_text(row["original_max_changes"]),
                json.dumps(row["filtered_y"], separators=(",", ":")),
            ])
        for cells in sheet:
            for cell in cells:
                cell.font = Font(name="Microsoft JhengHei", size=11)
                cell.alignment = Alignment(vertical="center", wrap_text=True)
                if isinstance(cell.value, (int, float)):
                    cell.number_format = "0"
        for cell in sheet[1]:
            cell.font = Font(name="Microsoft JhengHei", size=11, bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="243E59")
        for column in "ABC":
            sheet.column_dimensions[column].width = 10
        for column in "DE":
            sheet.column_dimensions[column].width = 35
        for column in "FGHIJK":
            sheet.column_dimensions[column].width = 20
        sheet.column_dimensions["L"].width = 70
        sheet.row_dimensions[1].height = 38
        for index in range(2, sheet.max_row + 1):
            sheet.row_dimensions[index].height = max(32, ceil(len(sheet.cell(index, 12).value) / 64) * 17)
        sheet.freeze_panes = "A2"
        table = Table(displayName=f"{group}_results", ref=f"A1:L{sheet.max_row}")
        table.tableStyleInfo = TableStyleInfo(name="TableStyleLight9", showRowStripes=True)
        sheet.add_table(table)
    temporary = workbook_path.with_name(workbook_path.stem + ".tmp.xlsx")
    try:
        workbook.save(temporary)
        temporary.replace(workbook_path)
    except PermissionError as exc:
        raise PermissionError(
            f"無法寫入 {workbook_path}，請關閉 Excel 中的活頁簿並確認目錄可寫入。"
            f"若已產生新版暫存檔，位置為 {temporary}。"
        ) from exc
    finally:
        workbook.close()


def run_experiments(output_dir=None, workbook_path=None):
    """執行兩組完整參數掃描，輸出圖檔、JSON 紀錄及 ablation.xlsx。"""
    import json
    from pathlib import Path

    require_excel_dependencies()
    base = Path(__file__).resolve().parent
    output_dir = Path(output_dir) if output_dir is not None else base / "addition" / "ablation"
    workbook_path = Path(workbook_path) if workbook_path is not None else base / "ablation.xlsx"
    output_dir.mkdir(parents=True, exist_ok=True)
    records = []
    experiments = [
        ("con_sweep", [(value, continuous_threshold * value) for value in conSeq]),
        ("csv_sweep", [(12, value) for value in csvSeq]),
    ]
    for experiment, parameters in experiments:
        for con_k, csv_k in parameters:
            folder = output_dir / experiment / f"con_{con_k}_csv_{csv_k}"
            folder.mkdir(parents=True, exist_ok=True)
            for name, sequence in poseSeq.items():
                result = analyze_sequence(sequence, con_k, csv_k)
                original_plot = folder / f"{name}_original.png"
                filtered_plot = folder / f"{name}_filtered.png"
                plot_sequence(range(len(sequence)), sequence, len(sequence), original_plot)
                plot_sequence(result["filtered_x"], result["filtered_y"], len(sequence), filtered_plot)
                records.append({
                    "experiment": experiment, "pose": name,
                    "con_k": con_k, "csv_k": csv_k, "total_frames": len(sequence),
                    **result,
                    "original_plot": str(original_plot.resolve()),
                    "filtered_plot": str(filtered_plot.resolve()),
                })
            print(f"{experiment}: con_k={con_k}, csv_k={csv_k}, {len(poseSeq)} sequences", flush=True)
    records_path = output_dir / "results.json"
    records_path.write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")
    export_excel(records, workbook_path)
    print(f"Completed {len(records)} experiments: {workbook_path}")
    return records


if __name__ == "__main__":
    run_experiments()
